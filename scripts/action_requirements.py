"""Write integrations/action/requirements.txt: what the action's `install: python` installs, pinned with hashes.

The runtime dependencies are exactly uv.lock's (versions and hashes; tests/test_integrations.py checks it), plus
the build backend (hatchling), because Limbowatch itself is built from the pinned release's source with
`--no-build-isolation`, so nothing is fetched unpinned. Run it whenever uv.lock changes, before a release:

    uv run python scripts/action_requirements.py        # network: PyPI, for hatchling's hashes
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "integrations/action/requirements.txt"
HEADER = """\
# The Limbowatch action's `install: python` (install.sh): every package pinned with its hashes, installed with
# pip --require-hashes. Runtime dependencies are uv.lock's; hatchling builds Limbowatch from the release's source.
# Generated by scripts/action_requirements.py; don't edit by hand.
"""


def _export(*extra: str) -> str:
    return subprocess.run(
        ["uv", "export", "--package", "limbowatch-cli", "--frozen", "--no-dev", "--no-emit-workspace", "--no-annotate",
         "--no-header", "--format", "requirements.txt", *extra],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout  # fmt: skip


def _names(text: str) -> set[str]:
    return {m.lower() for m in re.findall(r"(?m)^([A-Za-z0-9_.-]+)==", text)}


def main() -> int:
    runtime = _export()  # uv.lock's own hashes
    with tempfile.TemporaryDirectory() as tmp:
        pins, src, out = Path(tmp) / "pins.txt", Path(tmp) / "in.txt", Path(tmp) / "out.txt"
        pins.write_text(_export("--no-hashes"))
        src.write_text("hatchling\n")
        subprocess.run(  # the build backend, with the versions the runtime pins where they overlap (packaging)
            ["uv", "pip", "compile", "--universal", "--generate-hashes", "--python-version", "3.12", "--no-header",
             "--no-annotate", "--quiet", "-c", str(pins), str(src), "-o", str(out)],
            cwd=ROOT, check=True,
        )  # fmt: skip
        blocks = re.split(r"\n(?=[A-Za-z0-9])", out.read_text().strip())
    have = _names(runtime)
    build = [b for b in blocks if (m := re.match(r"([A-Za-z0-9_.-]+)==", b)) and m.group(1).lower() not in have]
    OUT.write_text(HEADER + runtime.rstrip() + "\n# the build backend\n" + "\n".join(build) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
